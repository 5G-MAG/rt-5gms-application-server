#!/usr/bin/env python3
'''Generate src/rt_5gms_as/oauth_scopes.py from the Mas_Configuration OpenAPI definitions (TS 26.512 annex A): the OAuth2 scope of each
operation, taken from the "security" of the operation.

usage: gen_oauth_scopes.py <directory with the TS26512_Mas_Configuration_*.yaml files> > src/rt_5gms_as/oauth_scopes.py
'''
import glob
import os
import sys

import yaml

print('# Generated by build_scripts/gen_oauth_scopes.py from the TS26512_Mas_Configuration_*.yaml definitions of',
      os.path.basename(os.path.dirname(os.path.abspath(sys.argv[1].rstrip('/')))) + '; do not edit.')
print('# The OAuth 2.0 scope that an operation of the Mas_Configuration API needs (TS 26.512 clause 6.6.3): method, path below the API version, scope')
print('OPERATION_SCOPES = [')
for f in sorted(glob.glob(os.path.join(sys.argv[1], 'TS26512_Mas_Configuration_*.yaml'))):
    d = yaml.safe_load(open(f))
    for path, item in d['paths'].items():
        for method, op in item.items():
            if method not in ('get', 'post', 'put', 'patch', 'delete'):
                continue
            scopes = [s for sec in op.get('security', []) for v in sec.values() for s in v]
            print(f"    ('{method.upper()}', '{path.rstrip('/')}', {repr(scopes[0]) if scopes else None}),")
print(']')
